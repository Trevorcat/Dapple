std::string lower(std::string s) {
  std::transform(s.begin(), s.end(), s.begin(), [](unsigned char c) { return char(std::tolower(c)); });
  return s;
}

bool iequals(const std::string& a, const std::string& b) { return lower(a) == lower(b); }

