// docs/architecture.md): replaces the coarse HSL baseline for this body.
#include "profiles/sony_ilce7rm5.inc"

ColorMatchProfile sonyIlce7rm5Match() {
  ColorMatchProfile m;
  m.hasMatrix = k_sony_ilce7rm5_hasMatrix;
  std::copy(std::begin(k_sony_ilce7rm5_matrix), std::end(k_sony_ilce7rm5_matrix), m.matrix);
  m.lutL = k_sony_ilce7rm5_lutL;
  m.lutAB = k_sony_ilce7rm5_lutAB;
  m.lutABMax = k_sony_ilce7rm5_lutABMax;
  m.lut.assign(std::begin(k_sony_ilce7rm5_lut), std::end(k_sony_ilce7rm5_lut));
  return m;
}

