CameraRegistry CameraRegistry::withBuiltins() {
  CameraRegistry r;
  r.generic_.id = "generic";
  r.generic_.displayName = "Generic camera";
  r.generic_.cfa = CfaKind::Unknown;
  r.generic_.rawExtensions = {".dng", ".arw", ".raf", ".cr2", ".cr3", ".nef", ".nrw", ".orf",
                              ".rw2", ".pef", ".srw", ".3fr", ".iiq", ".x3f", ".erf", ".kdc"};
  r.generic_.baselineContrast = 10.f;
  for (auto& p : builtinProfiles()) r.add(std::move(p));
  return r;
}

void CameraRegistry::add(CameraProfile profile) {
  for (auto& ext : profile.rawExtensions) ext = lower(ext);
  auto it = std::find_if(profiles_.begin(), profiles_.end(),
                         [&](const CameraProfile& p) { return p.id == profile.id; });
  if (it != profiles_.end()) {
    *it = std::move(profile);
  } else {
    profiles_.push_back(std::move(profile));
  }
}

const CameraProfile& CameraRegistry::resolve(const std::string& make, const std::string& model) const {
  const CameraProfile* makerFallback = nullptr;
  for (const auto& p : profiles_) {
    if (!iequals(p.make, make)) continue;
    if (p.model.empty()) {
      makerFallback = &p;
    } else if (iequals(p.model, model)) {
      return p;
    }
  }
  return makerFallback ? *makerFallback : generic_;
}

bool CameraRegistry::isRawExtension(const std::string& lowerExt) const {
  auto has = [&](const CameraProfile& p) {
    return std::find(p.rawExtensions.begin(), p.rawExtensions.end(), lowerExt) != p.rawExtensions.end();
  };
  return has(generic_) || std::any_of(profiles_.begin(), profiles_.end(), has);
}

const char* toString(CfaKind kind) {
  switch (kind) {
    case CfaKind::Bayer: return "Bayer";
    case CfaKind::XTrans: return "X-Trans";
    case CfaKind::None: return "none";
    default: return "unknown";
  }
}

